const { chromium, devices, ROOT, PEER, GL, MP_ARGS, shot } = require('./lib');
(async () => {
  const browser = await chromium.launch({ args: GL });
  const page = await browser.newPage({ viewport: { width: 960, height: 540 }, deviceScaleFactor: 1 });
  const logs = [], ok = [], bad = [];
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') logs.push(m.type() + ': ' + m.text().slice(0, 200)); });
  page.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message));
  const check = async (name, fn) => { try { const r = await page.evaluate(fn); (r === true ? ok : bad).push(name + (r === true ? '' : ' -> ' + JSON.stringify(r))); } catch (e) { bad.push(name + ' -> ' + e.message.slice(0, 120)); } };
  const vis = (id) => `!document.getElementById('${id}').classList.contains('hidden')`;
  await page.goto(ROOT + '/index.html?debug=1');
  await page.evaluate(() => { try { localStorage.clear(); } catch (e) {} });
  await page.reload();
  await page.waitForFunction(() => window.game && !document.getElementById('menu').classList.contains('hidden'), null, { timeout: 120000 });
  await check('title menu visible', `${vis('menu')} && game.state === 'title'`);
  await page.click('#btn-story');
  await page.waitForTimeout(1500);
  await check('story starts at period 1 with no progress', `game.state === 'playing' && game.mode === 'story' && game.chapter === 0`);
  await check('HUD shown, helper eye hidden by default', `${vis('hud')} && document.getElementById('eye').style.visibility === 'hidden'`);
  await page.keyboard.press('Escape'); await page.waitForTimeout(300);
  await check('Esc pauses', `game.state === 'paused' && ${vis('pause')}`);
  await page.click('#btn-resume'); await page.waitForTimeout(300);
  await check('resume', `game.state === 'playing' && !${vis('pause')}`);
  await page.keyboard.press('Escape'); await page.waitForTimeout(300);
  await page.click('#btn-restart'); await page.waitForTimeout(500);
  await check('restart same period', `game.state === 'playing' && game.chapter === 0 && game.t < 3`);
  await page.keyboard.press('Escape'); await page.waitForTimeout(300);
  await page.click('#btn-quit'); await page.waitForTimeout(600);
  await check('main menu from pause', `game.state === 'title' && ${vis('title')} && !${vis('hud')}`);
  await page.click('#btn-settings'); await page.waitForTimeout(200);
  for (const id of ['set-retro', 'set-shadows', 'set-meter', 'set-subs']) await page.click('#' + id);
  await page.waitForTimeout(800);
  await check('settings toggle and save', `(() => { const s = JSON.parse(localStorage.getItem('madiclass.settings')); return s.retro === false && s.meter === true && s.subs === false; })()`);
  for (const id of ['set-retro', 'set-meter', 'set-subs']) await page.click('#' + id);
  await page.click('#settings .back'); await page.waitForTimeout(200);
  await check('back to title', `${vis('title')}`);
  await page.click('#btn-how'); await page.waitForTimeout(200);
  await check('how to play opens', `${vis('how')}`);
  await page.click('#how .back');
  await page.evaluate(() => localStorage.setItem('madiclass.progress', '2'));
  await page.click('#btn-story'); await page.waitForTimeout(300);
  await check('chapter select shows 3 unlocked + 1 locked', `(() => { const b = [...document.querySelectorAll('#chapter-list button')]; return b.length === 4 && b.filter(x => !x.disabled).length === 3 && b[3].disabled && b[3].innerText.includes('???'); })()`);
  await page.click('#chapter-list button:nth-child(3)'); await page.waitForTimeout(1500);
  await check('period 3 starts from chapter select', `game.state === 'playing' && game.chapter === 2`);
  await page.evaluate(() => game.completeChapter()); await page.waitForTimeout(300);
  await check('period complete screen offers NEXT PERIOD', `${vis('end')} && document.getElementById('btn-again').innerText === 'NEXT PERIOD' && localStorage.getItem('madiclass.progress') === '3'`);
  await page.click('#btn-again'); await page.waitForTimeout(1200);
  await check('NEXT PERIOD starts period 4', `game.state === 'playing' && game.chapter === 3`);
  await page.evaluate(() => game.finish('caught')); await page.waitForTimeout(300);
  await check('failing offers RETRY PERIOD', `document.getElementById('btn-again').innerText === 'RETRY PERIOD'`);
  await page.click('#btn-menu'); await page.waitForTimeout(600);
  await check('MAIN MENU from end screen', `game.state === 'title'`);
  await page.click('#btn-free'); await page.waitForTimeout(1500);
  await check('free class starts', `game.state === 'playing' && game.mode === 'free'`);
  await page.evaluate(() => { const g = game; g.cutscene = false; g.lockBully = false; g.quirks = new Set(); g.alarmOn = false; g.dancing = false; g.echoable = { id: 't_quiet', text: 'Quiet.', until: g.t + 5 }; }); // (no quirks: from his deaf side an echo would not count)
  await page.keyboard.press('r'); await page.waitForTimeout(400);
  await check('R repeats him', `game.echoStreak === 1 && document.getElementById('subtitle').innerText.includes('qUiEt')`);
  await page.evaluate(() => { const g = game; g.qBusy = false; g.cutscene = false; g.lockBully = false; if (g.choice) g.pickChoice(-1); });
  await page.keyboard.press('t'); await page.waitForTimeout(400);
  await check('T opens the question picker', `${vis('choices')} && document.querySelectorAll('#choices-list button').length === 3`);
  await page.keyboard.press('2'); await page.waitForTimeout(700);
  await check('2 asks the question and raises your hand', `!${vis('choices')} && game.qCount === 1 && game.handT > 0`);
  await page.evaluate(() => { game.yaw = 0.15; game.pitch = -0.15; });
  await page.waitForTimeout(600);
  await page.screenshot({ path: shot('ui_hand.png') });
  await page.evaluate(() => { game.yaw = 1.52; game.pitch = -0.05; });
  await page.keyboard.down('e'); await page.waitForTimeout(2500);
  await check('holding E whispers to Sam', `!!game.talk && game.talk.friend.name === 'Sam'`);
  await page.screenshot({ path: shot('ui_sam.png') });
  await page.keyboard.up('e'); await page.waitForTimeout(300);
  await check('releasing E stops', `!game.talk`);
  await page.keyboard.down('q'); await page.waitForTimeout(800);
  await check('holding Q raises the phone', `game.phone.up === true`);
  await page.keyboard.up('q');
  console.log('PASS (' + ok.length + '):\n  ' + ok.join('\n  '));
  console.log('FAIL (' + bad.length + '):\n  ' + bad.join('\n  '));
  console.log(logs.slice(0, 10).join('\n') || 'no console errors');
  await browser.close();
})();
