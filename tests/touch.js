const { chromium, devices, ROOT, PEER, GL, MP_ARGS, shot } = require('./lib');
(async () => {
  const browser = await chromium.launch({ args: GL });
  const ctx = await browser.newContext({ ...devices['iPhone 13 landscape'] });
  const page = await ctx.newPage();
  const logs = [], ok = [], bad = [];
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') logs.push(m.type() + ': ' + m.text().slice(0, 200)); });
  page.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message));
  const check = async (name, fn) => { const r = await page.evaluate(fn); (r === true ? ok : bad).push(name + (r === true ? '' : ' -> ' + JSON.stringify(r))); };
  const touch = (sel, type) => page.evaluate(([sel, type]) => {
    const el = document.querySelector(sel); const r = el.getBoundingClientRect();
    const t = new Touch({ identifier: 7, target: el, clientX: r.x + r.width / 2, clientY: r.y + r.height / 2 });
    el.dispatchEvent(new TouchEvent(type, { touches: type === 'touchend' ? [] : [t], changedTouches: [t], bubbles: true, cancelable: true }));
  }, [sel, type]);
  await page.goto(ROOT + '/index.html?debug=1');
  await page.waitForFunction(() => window.game && !document.getElementById('menu').classList.contains('hidden'), null, { timeout: 120000 });
  await check('touch layout detected', `document.body.classList.contains('touch')`);
  await page.tap('#btn-free'); await page.waitForTimeout(1500);
  await check('free class starts by tap', `game.state === 'playing'`);
  await check('5 touch buttons visible (with PRANK)', `[...document.querySelectorAll('.tbtn')].filter(b => b.offsetParent !== null).length === 5`);
  // drag on the canvas to look around
  const y0 = await page.evaluate(() => game.yaw);
  await page.evaluate(() => {
    const c = document.getElementById('view');
    const mk = (x) => new Touch({ identifier: 1, target: c, clientX: x, clientY: 200 });
    c.dispatchEvent(new TouchEvent('touchstart', { touches: [mk(400)], changedTouches: [mk(400)], bubbles: true, cancelable: true }));
    for (let x = 400; x >= 250; x -= 10) c.dispatchEvent(new TouchEvent('touchmove', { touches: [mk(x)], changedTouches: [mk(x)], bubbles: true, cancelable: true }));
    c.dispatchEvent(new TouchEvent('touchend', { touches: [], changedTouches: [mk(250)], bubbles: true, cancelable: true }));
  });
  const frames = async (sec) => { const t0 = await page.evaluate(() => game.t); await page.waitForFunction((t) => game.t >= t, t0 + sec, { timeout: 30000 }); };
  const fps0 = await page.evaluate(() => game.t); await page.waitForTimeout(2000); const fps1 = await page.evaluate(() => game.t);
  console.log('game seconds per 2 real seconds:', (fps1 - fps0).toFixed(2));
  await frames(0.1);
  await check('dragging turns the view', `game.yaw > ${y0} + 0.3`);
  await page.evaluate(() => { game.yaw = -1.52; game.pitch = -0.05; });
  await touch('#btn-talk', 'touchstart'); await page.waitForTimeout(2000); await frames(0.5);
  await check('hold TALK whispers to Nora', `!!game.talk && game.talk.friend.name === 'Nora' && document.getElementById('btn-talk').classList.contains('active')`);
  await touch('#btn-talk', 'touchend'); await page.waitForTimeout(300);
  await check('release TALK stops', `!game.talk`);
  await page.evaluate(() => { const g = game; g.yaw = 0; g.cutscene = false; g.lockBully = false; g.echoable = { id: 't_still', text: 'Sit... still.', until: g.t + 5 }; });
  await page.waitForTimeout(200);
  await check('ECHO button lights up when you can repeat him', `document.getElementById('btn-echo').classList.contains('ready')`);
  await touch('#btn-echo', 'touchstart'); await page.waitForTimeout(400);
  await check('tap ECHO repeats him', `game.echoStreak === 1`);
  await page.evaluate(() => { const g = game; g.qBusy = false; g.cutscene = false; g.lockBully = false; });
  await touch('#btn-ask', 'touchstart'); await page.waitForTimeout(400);
  await check('tap ASK opens the choices', `!document.getElementById('choices').classList.contains('hidden')`);
  await page.screenshot({ path: shot('touch_choices.png') });
  await page.tap('#choices-list button:nth-child(1)'); await page.waitForTimeout(400);
  await check('tapping a choice asks it', `document.getElementById('choices').classList.contains('hidden') && game.qCount === 1`);
  await touch('#btn-phone', 'touchstart'); await page.waitForTimeout(600);
  await check('hold PHONE raises phone', `game.phone.up === true`);
  await touch('#btn-phone', 'touchend');
  // pranks: hold PRANK to aim (the other buttons become DROP / BALL / SWAP), let go to throw
  await page.evaluate(() => { const g = game; g.__uw = g.updateWatching; g.updateWatching = function () { g.__uw.call(g); for (const p of g.players) { p.watching = false; p.lookDot = -1; } };
    g.me.foldT = 0; g.yaw = 0; g.pitch = 0.1; g.cutscene = false; g.lockBully = false; });
  await touch('#btn-prank', 'touchstart'); await page.waitForTimeout(700);
  await check('hold PRANK: aiming, buttons become DROP / BALL / SWAP', `!!game.me.aim && ['btn-talk', 'btn-ask', 'btn-echo'].map((id) => document.getElementById(id).textContent).join('/') === 'DROP/BALL/SWAP'`);
  await page.screenshot({ path: shot('touch_prank.png') });
  await touch('#btn-echo', 'touchstart'); await page.waitForTimeout(300);
  await check('tap SWAP: a paper plane', `!!game.me.aim && game.me.aim.kind === 'plane' && document.getElementById('btn-ask').textContent === 'PLANE'`);
  await touch('#btn-prank', 'touchend'); await page.waitForTimeout(500);
  await check('let go of PRANK: thrown, buttons back to TALK / ASK / ECHO', `game.stats.throws === 1 && !game.me.aim && document.getElementById('btn-talk').textContent === 'TALK'`);
  await page.evaluate(() => { game.updateWatching = game.__uw; });
  await page.tap('#btn-pause'); await page.waitForTimeout(300);
  await check('pause button', `game.state === 'paused'`);
  await page.tap('#btn-resume'); await page.waitForTimeout(300);
  await check('resume', `game.state === 'playing'`);
  console.log('PASS (' + ok.length + '):\n  ' + ok.join('\n  '));
  console.log('FAIL (' + bad.length + '):\n  ' + bad.join('\n  '));
  console.log(logs.slice(0, 10).join('\n') || 'no console errors');
  await browser.close();
})();
